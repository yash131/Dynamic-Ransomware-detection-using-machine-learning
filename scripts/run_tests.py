"""
Run the bundled test files (and error paths) through the REAL API + REAL models and write
TEST_RESULTS.md / tests_output/test_results.json.   Usage:  python scripts/run_tests.py [--extra-pe a.exe b.dll ...]
Nothing is mocked: requests go through the FastAPI app and every prediction comes from the pickled models.
"""
import argparse, json, pathlib, sys, datetime, platform
ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from fastapi.testclient import TestClient
from app.main import app, service
from app.pe_features import extract_features

ap = argparse.ArgumentParser(); ap.add_argument("--extra-pe", nargs="*", default=[])
args = ap.parse_args()

checks, out = [], {"generated": datetime.datetime.now().isoformat(timespec="seconds"), "python": platform.python_version()}
def check(name, ok, detail=""):
    checks.append((name, bool(ok), detail)); print(("PASS " if ok else "FAIL ") + name, detail)

with TestClient(app) as c:
    h = c.get("/api/health").json(); out["health"] = h
    check("all 5 models loaded", len(h["models_loaded"]) == 5, str(h["models_loaded"]))

    scans = {}
    for name, expect in [("benign_sample.bin", "Benign"), ("simulated_malicious_sample.bin", "Malicious")]:
        data = (ROOT / "test_files" / name).read_bytes()
        r = c.post("/api/scan", files={"file": (name, data, "application/octet-stream")})
        j = r.json(); scans[name] = j
        check(f"upload {name} -> HTTP 200", r.status_code == 200)
        check(f"{name} verdict is {expect}", j.get("verdict") == expect, f"verdict={j.get('verdict')} votes={j.get('votes')}")
    out["scans"] = scans

    r = c.post("/api/scan", files={"file": ("notes.txt", b"hello world", "text/plain")})
    check("non-PE rejected with 422 (no fake prediction)", r.status_code == 422 and "verdict" not in r.json())
    r = c.post("/api/scan", files={"file": ("e.bin", b"", "application/octet-stream")})
    check("empty file -> 400", r.status_code == 400)
    r = c.post("/api/scan")
    check("missing file field -> 400 JSON error", r.status_code == 400 and "error" in r.json())
    r = c.post("/api/scan-sample/..%2F..%2Fetc%2Fpasswd")
    check("path traversal on sample endpoint blocked", r.status_code == 404)
    r = c.post("/api/scan", files={"file": ('a"<b>/../../x.exe', (ROOT / "test_files/benign_sample.bin").read_bytes(), "application/octet-stream")})
    check("hostile filename sanitised", r.status_code == 200 and r.json()["file"]["name"] == "x.exe", r.json()["file"]["name"])
    check("security headers present", all(k in c.get("/").headers for k in ("content-security-policy", "x-frame-options", "x-content-type-options")))
    check("API docs surface disabled", c.get("/docs").status_code == 404)

    extra = []
    for p in args.extra_pe:
        d = pathlib.Path(p).read_bytes()
        j = c.post("/api/scan", files={"file": (pathlib.Path(p).name, d, "application/octet-stream")}).json()
        extra.append({"file": pathlib.Path(p).name, "verdict": j.get("verdict"), "votes": j.get("votes"),
                      "p_malicious": {m["model"]: m["p_malicious"] for m in j.get("models", [])}, "features": j.get("model_features_used")})
    out["extra_real_benign_pe"] = extra

out["checks"] = [{"name": n, "pass": ok, "detail": d} for n, ok, d in checks]
(ROOT / "tests_output").mkdir(exist_ok=True)
(ROOT / "tests_output/test_results.json").write_text(json.dumps(out, indent=2))

# ---- markdown report
L = ["# Test results", "",
     f"Generated {out['generated']} · Python {out['python']} · feature mapping status: **{service.mapping_status}**", "",
     "All predictions below were produced by the five pickled models in `models/` through the live API code path "
     "(`POST /api/scan`). Nothing is hard-coded. Decision rule: a model says Benign when P(benign) > 0.4; overall verdict = majority vote.", ""]
L += ["## How to read these results", "",
      "* Both files are **inert, header-only PE stubs** generated by `scripts/make_test_files.py` (no code, entry point 0, `.bin` extension).",
      "* The benign stub reuses the header values of a real MSVC-built launcher (so it scores identically to that real file, see below).",
      "* The 'simulated malicious' stub is **not real malware**. Its header profile (legacy linker/OS versions, no debug directory, no DllCharacteristics) was chosen after probing the models' decision surface, so that it exercises the Malicious path.",
      "* Therefore these two verdicts demonstrate that **the pipeline runs end to end with real model outputs**. They are NOT an independent measure of detection accuracy. For accuracy see the held-out metrics in `reference/tables/model_comparison.csv`.",
      "* The 7 model inputs are an **inferred** mapping until `scripts/recover_feature_selection.py` is run on the original CSV (see README).", ""]
for name, j in scans.items():
    L += [f"## {name}", "", f"SHA-256 `{j['file']['sha256']}` · {j['file']['size_bytes']} bytes", "",
          f"**Verdict: {j['verdict']}** ({j['votes']['malicious']} malicious / {j['votes']['benign']} benign, mean P(malicious) = {j['mean_p_malicious']:.4f})", "",
          "| Model | Label | P(malicious) | P(benign) |", "|---|---|---|---|"]
    L += [f"| {m['model']} | {m['label']} | {m['p_malicious']:.4f} | {m['p_benign']:.4f} |" for m in j["models"]]
    L += ["", "Model inputs: `" + json.dumps(j["model_features_used"]) + "`", ""]
if extra:
    L += ["## Extra check: real benign PE files (not shipped)", "",
          "Genuine, benign, MSVC-built Windows binaries (setuptools launcher stubs) found on the build machine; parsed only, never executed.", "",
          "| File | Verdict | Votes (mal/ben) | P(malicious) per model |", "|---|---|---|---|"]
    L += [f"| {e['file']} | {e['verdict']} | {e['votes']['malicious']}/{e['votes']['benign']} | " + ", ".join(f"{k} {v:.3f}" for k, v in e["p_malicious"].items()) + " |" for e in extra]
    L.append("")
L += ["## Checks", "", "| Check | Result | Detail |", "|---|---|---|"]
L += [f"| {n} | {'PASS' if ok else 'FAIL'} | {d} |" for n, ok, d in checks]
(ROOT / "TEST_RESULTS.md").write_text("\n".join(L) + "\n")
print(f"\n{sum(ok for _, ok, _ in checks)}/{len(checks)} checks passed")
sys.exit(0 if all(ok for _, ok, _ in checks) else 1)
